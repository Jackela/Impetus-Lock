def migration_config(connection: Connection) -> Config:
    """Configure Alembic to use the test's isolated PostgreSQL schema."""
    config = Config()
    config.set_main_option("script_location", str(SERVER_DIR / "alembic"))
    config.attributes["connection"] = connection
    return config


def verify_head_schema(connection: Connection) -> None:
    """Compare every migrated table with the production Alembic metadata."""
    config = migration_config(connection)
    upgrade(config, "head")
    connection.commit()
    check(config)
    connection.execute(text("""ALTER TABLE tasks ALTER lock_ids SET DEFAULT '["drift"]'::json"""))
    connection.commit()
    with pytest.raises(AutogenerateDiffsDetected, match=r"modify_default.*'tasks', 'lock_ids'"):
        check(config)


def verify_lock_migration(connection: Connection) -> None:
    """Roundtrip real task rows across the historical ARRAY to JSON revision."""
    config = migration_config(connection)
    upgrade(config, LOCK_ARRAY_REVISION)
    locks = [
        "old-lock",
        "with,comma",
        'quoted"',
        "back\\slash",
        "{brace}",
        "锁句\n",
        "NULL",
        "",
        "old-lock",
    ]
    insert = text(
        """
        INSERT INTO tasks (id, content, lock_ids, created_at, updated_at, version)
        VALUES (:id, :content, CAST(:locks AS varchar[]), now(), now(), :version)
        """
    )
    connection.execute(
        insert, {"id": uuid4(), "content": "Multi-lock draft", "locks": locks, "version": 7}
    )
    connection.execute(
        insert, {"id": uuid4(), "content": "Unlocked draft", "locks": [], "version": 1}
    )
    connection.commit()

    for operation, revision, column_type in (
        (upgrade, LOCK_JSON_REVISION, "json"),
        (downgrade, LOCK_ARRAY_REVISION, "character varying[]"),
        (upgrade, LOCK_JSON_REVISION, "json"),
    ):
        operation(config, revision)
        assert MigrationContext.configure(connection).get_current_revision() == revision
        rows = connection.execute(
            text(
                "SELECT content, lock_ids, version, pg_typeof(lock_ids)::text "
                "FROM tasks ORDER BY content"
            )
        ).all()
        assert rows == [
            ("Multi-lock draft", locks, 7, column_type),
            ("Unlocked draft", [], 1, column_type),
        ]
        default_task = uuid4()
        assert (
            connection.execute(
                text(
                    """
                INSERT INTO tasks (id, content, created_at, updated_at, version)
                VALUES (:id, 'Default lock list', now(), now(), 0) RETURNING lock_ids
                """
                ),
                {"id": default_task},
            ).scalar_one()
            == []
        )
        connection.execute(text("DELETE FROM tasks WHERE id = :id"), {"id": default_task})
        connection.commit()


def verify_schema(connection: Connection) -> str:
    """Check the WeChat model schema and save a run with a default receipt."""
    metadata = MetaData()
    for name, table in Base.metadata.tables.items():
        if name.startswith("wechat_"):
            table.to_metadata(metadata)
    assert set(metadata.tables) == WECHAT_TABLES

    inspector = inspect(connection)
    for name, table in metadata.tables.items():
        assert inspector.get_pk_constraint(name)["constrained_columns"] == [
            column.name for column in table.primary_key
        ]

    context = MigrationContext.configure(
        connection,
        opts={
            "compare_server_default": True,
            "include_object": lambda _obj, name, kind, *_: kind != "table" or name in WECHAT_TABLES,
        },
    )
    assert compare_metadata(context, metadata) == []

    run_id = str(uuid4())
    connection.execute(
        text(
            """
            INSERT INTO wechat_runs (id, subject, start_request_id, version,
                                     initial, state, created_at)
            VALUES (:run_id, 'migration-fixture', 'start', 1, '{}', '{}', now())
            """
        ),
        {"run_id": run_id},
    )
    default_receipt = connection.execute(
        text(
            """
            INSERT INTO wechat_run_receipts (run_id, request_id)
            VALUES (:run_id, 'turn') RETURNING outcome, attempt_version
            """
        ),
        {"run_id": run_id},
    ).one()
    assert tuple(default_receipt) == ("committed", None)
    return run_id


def verify_wechat_migration(connection: Connection) -> None:
    """Apply the full chain and inspect the data before and after the WeChat revision."""
    config = migration_config(connection)
    upgrade(config, PREVIOUS_REVISION)

    old_tables = set(inspect(connection).get_table_names())
    owner = connection.execute(
        text(
            "INSERT INTO users (email, password_hash) VALUES "
            "('legacy@example.test', 'fixture-hash') RETURNING id"
        )
    ).scalar_one()
    task = uuid4()
    connection.execute(
        text(
            """
            INSERT INTO tasks (id, user_id, content, lock_ids, created_at, updated_at, version)
            VALUES (:task, :owner, 'Original draft', '["old-lock"]', now(), now(), 7)
            """
        ),
        {"task": task, "owner": owner},
    )
    connection.execute(
        text(
            """
            INSERT INTO intervention_actions (
                id, task_id, action_type, action_id, lock_id, content,
                anchor, mode, context, issued_at, created_at
            )
            VALUES (
                :action, :task, 'provoke', 'old-action', 'old-lock', 'Preserved lock',
                '{"type": "pos", "from": 0}', 'muse', 'Original draft', now(), now()
            )
            """
        ),
        {"action": uuid4(), "task": task},
    )
    connection.commit()

    legacy_data = text(
        """
        SELECT users.email, tasks.content, tasks.lock_ids, tasks.version,
               intervention_actions.action_id, intervention_actions.content
        FROM tasks
        JOIN users ON users.id = tasks.user_id
        JOIN intervention_actions ON intervention_actions.task_id = tasks.id
        WHERE tasks.id = :task
        """
    )
    expected_legacy = (
        "legacy@example.test",
        "Original draft",
        ["old-lock"],
        7,
        "old-action",
        "Preserved lock",
    )
    for operation, revision in (
        (upgrade, WECHAT_REVISION),
        (downgrade, PREVIOUS_REVISION),
        (upgrade, WECHAT_REVISION),
    ):
        operation(config, revision)
        assert MigrationContext.configure(connection).get_current_revision() == revision
        tables = set(inspect(connection).get_table_names())
        if revision == PREVIOUS_REVISION:
            assert tables == old_tables
        else:
            assert tables == old_tables | WECHAT_TABLES
            run_id = verify_schema(connection)
            connection.commit()
            upgrade(config, WEB_RECEIPT_REVISION)
            check(config)
            retained_receipt = connection.execute(
                text(
                    """
                    SELECT wechat_runs.version, wechat_run_receipts.outcome
                    FROM wechat_runs JOIN wechat_run_receipts
                        ON wechat_runs.id = wechat_run_receipts.run_id
                    WHERE wechat_runs.id = :run_id AND wechat_run_receipts.request_id = 'turn'
                    """
                ),
                {"run_id": run_id},
            ).one()
            assert tuple(retained_receipt) == (1, "committed")
            connection.execute(
                text(
                    """
                    INSERT INTO intervention_receipts (
                        user_id, task_id, key_digest, action_id, expires_at
                    )
                    VALUES (:owner, :task, :digest, 'old-action', now() + interval '15 seconds')
                    """
                ),
                {"task": task, "owner": owner, "digest": "a" * 64},
            )
            connection.commit()
            downgrade(config, WECHAT_REVISION)
            assert "intervention_receipts" not in inspect(connection).get_table_names()
            assert tuple(connection.execute(legacy_data, {"task": task}).one()) == expected_legacy
            assert (
                connection.execute(
                    text("SELECT version FROM wechat_runs WHERE id = :run_id"), {"run_id": run_id}
                ).scalar_one()
                == 1
            )
            connection.commit()
            upgrade(config, WEB_RECEIPT_REVISION)
            assert (
                connection.execute(text("SELECT count(*) FROM intervention_receipts")).scalar_one()
                == 0
            )
        assert tuple(connection.execute(legacy_data, {"task": task}).one()) == expected_legacy
        connection.commit()


@pytest.fixture
async def migration_connection() -> AsyncIterator[AsyncConnection]:
    """Use a fresh schema without modifying other tests or existing data."""
    schema = f"migration_{uuid4().hex}"
    engine = create_async_engine(POSTGRES_TEST_URL)
    try:
        async with engine.begin() as connection:
            await connection.execute(CreateSchema(schema))
        migrated_engine = create_async_engine(
            POSTGRES_TEST_URL, connect_args={"server_settings": {"search_path": schema}}
        )
        try:
            async with migrated_engine.connect() as connection:
                yield connection
        finally:
            await migrated_engine.dispose()
            async with engine.begin() as connection:
                await connection.execute(DropSchema(schema, cascade=True))
    finally:
        await engine.dispose()


