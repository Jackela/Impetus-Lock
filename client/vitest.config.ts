import { defineConfig } from "vitest/config";
import react from "@vitejs/plugin-react";
import { resolve } from "node:path";
import type { InlineConfig, Reporter } from "vitest/node";

const criticalFiles = [
  "src/services/LockManager.ts",
  "src/components/Editor/TransactionFilter.ts",
  "src/services/ContentInjector.ts",
  "src/utils/prosemirror-helpers.ts",
  "src/utils/textRange.ts",
  "src/utils/editorMarkdown.ts",
];

// Native perFile thresholds cover unexecuted files, but cannot reject a file
// absent from the report. Resolve the fixed inventory against Vitest's actual
// root (including isolated fixtures), rather than this config file's location.
let coverageRoot: string;
const criticalInventory: Reporter = {
  onInit(vitest) {
    coverageRoot = vitest.config.root;
  },
  onCoverage(coverage) {
    if (
      !coverage ||
      typeof coverage !== "object" ||
      !("files" in coverage) ||
      typeof coverage.files !== "function"
    ) {
      throw new Error("Critical coverage report is unavailable");
    }
    const reportedFiles: string[] = coverage.files();
    for (const file of criticalFiles) {
      if (!reportedFiles.some((reported) => resolve(reported) === resolve(coverageRoot, file))) {
        console.error(`Missing critical coverage: ${file}`);
        process.exitCode = 1;
      }
    }
  },
};

const testPool =
  (process.env.VITEST_POOL as "forks" | "threads" | "vmThreads" | undefined) ?? "forks";

// Per-file 80% floor for each critical file, expressed as vitest glob
// thresholds (a glob key is evaluated against every file it matches). The
// leading `**/` is required for the same reason as in `coverage.include`.
const criticalThresholds: Record<string, { lines: number }> = {};
for (const file of criticalFiles) {
  criticalThresholds[`**/${file}`] = { lines: 80 };
}

// CI additionally emits a JUnit report for dashboards/report ingestion; the
// local run stays on the interactive default reporter.
const reporters: NonNullable<InlineConfig["reporters"]> = process.env.CI
  ? ["dot", ["junit", { outputFile: "reports/vitest-junit.xml" }], criticalInventory]
  : ["default", criticalInventory];

export default defineConfig({
  plugins: [react()],
  test: {
    globals: true,
    reporters,
    environment: "jsdom",
    setupFiles: "./vitest.setup.ts",
    // Every global installed by `vitest.setup.ts` is defined directly (not via
    // `vi.stubGlobal`), so resetting mock state between tests is safe here.
    clearMocks: true,
    restoreMocks: true,
    // jsdom + a cold Vite transform can exceed Vitest's 5s defaults on shared
    // runners; the slower suites legitimately take 1-2s per test.
    testTimeout: 10000,
    hookTimeout: 10000,
    include: ["tests/**/*.{test,spec}.{ts,tsx}", "src/**/*.{test,spec}.{ts,tsx}"],
    exclude: ["tests/e2e/**", "node_modules"],
    coverage: {
      provider: "v8",
      // Glob patterns (leading `**/`) are required: vitest 5 appends `/**` to
      // non-glob patterns and treats them as directories, which would match
      // nothing and let the lines threshold pass vacuously.
      //
      // Scope: the whole shipped source tree (not only the critical
      // inventory), so untested modules are visible in the report and dilute
      // the overall number instead of being invisible.
      include: ["**/src/**/*.{ts,tsx}"],
      exclude: [
        "**/src/**/*.{test,spec}.{ts,tsx}",
        "**/src/**/__tests__/**",
        "**/src/**/__mocks__/**",
        "**/src/**/*.d.ts",
        // Vite entry point: no logic, unreachable from tests.
        "**/src/main.tsx",
        // Generated by `npm run api:generate` (openapi-typescript), never hand-edited.
        "**/src/types/api.generated.ts",
        "**/src/**/*.stories.{ts,tsx}",
        "**/node_modules/**",
        "**/dist/**",
        "**/coverage/**",
      ],
      reporter: ["text", "json", "json-summary", "html"],
      thresholds: {
        // Overall floor for the whole `src/**` tree, set to the measured value
        // minus 3 percentage points so ordinary churn does not fail the build.
        //
        // Measured with `npm run test -- --coverage` (986 tests, 92 files):
        //   lines 81.72 | statements 80.40 | branches 78.59 | functions 75.31
        // The critical inventory below keeps its much stricter per-file floor.
        lines: 78,
        statements: 77,
        functions: 72,
        branches: 75,
        // Per-file 80% floor for the lock-critical inventory (glob keys apply
        // to every matching file individually). `criticalInventory` above
        // additionally rejects a critical file that is missing from the report.
        ...criticalThresholds,
      },
    },
    // The supported Vitest/jsdom runtime intersection is declared in package
    // `engines` as ^22.13.0 || ^24.0.0. CI and Docker build stages run Node 24.
    //
    // Vitest 4 removed `poolOptions.{threads,forks}.single`; per-file
    // isolation in the standard pools replaces it (the old single-worker
    // mode's shared registry let file-scoped vi.mock instances bleed across
    // test files). Vitest 5 additionally ships the mock-isolation fix
    // (PR #10267) for the cross-file vi.mock leak (vitest#9957) that
    // motivated the vitest 4.0.18 freeze.
    pool: testPool,
  },
});
